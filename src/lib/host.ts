/**
 * Настоящее ли это приложение или показ вёрстки в браузере.
 *
 * Одной проверки `__TAURI_INTERNALS__` не хватает: заглушка ставит этот ключ
 * сама, иначе бы через неё не проходили вызовы. Поэтому у заглушки есть своя
 * метка, и всё, что зовёт плагины Tauri напрямую — окно, буфер, файлы, —
 * спрашивает именно здесь.
 */
export function isTauri(): boolean {
  return '__TAURI_INTERNALS__' in window && !('__OSUCUP_MOCK__' in window);
}
